def series_of(text: str) -> str:
    """공고 본문에서 계열을 판정한다. 겹치면 '|' 로 잇는다.

    공고 상당수는 지정 사유를 본문에 적지 않고 표의 '비고' 칸에만 적는데
    그 칸은 글꼴이 깨져 안 읽히는 경우가 많다. 그래서 '미분류'가 흔하다.
    통제군 오염 점검은 계열이 아니라 구역의 위치와 효력일로 판단해야 한다."""
    import re as _re
    hit = [n for n, pats in NOTICE_SERIES if any(_re.search(p, text) for p in pats)]
    return "|".join(hit) or "미분류"


